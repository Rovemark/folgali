// Pages (fans and projects): create, administer, publish, follow, home timeline and owner exit.
import test from 'node:test'
import assert from 'node:assert/strict'
import { STRUCTURE } from '../../packages/protocol/src/index.js'
import { DAY, codeOf, errorOf, fresh } from '../helpers/network.js'

const base = () => {
  const x = fresh()
  return Object.assign(x, { dono: x.rover(), admin: x.rover(), fa: x.rover(), fa2: x.rover() })
}
const create = (x, owner, name = 'Fãs de planilha') => x.ok(owner, 'pagina-criar', { nome: name, descricao: 'Novidades e dicas', tema: 'planilhas' }).id
const notices = (x, r) => x.s.listar(r.uid, { limite: 50 }, x.m.relogio.agora).itens.map((n) => n.tipo)

test('create a page: the creator is owner and administrator; the read brings the envelope; unique name; a new account waits 1 day; at most 5', () => {
  const x = base()
  const p = create(x, x.dono)
  const d = x.s.pageDetail(p, {})
  assert.deepEqual([d.id, d.nome, d.tema, d.dono.uid, d.seguidores], [p, 'Fãs de planilha', 'planilhas', x.dono.uid, 0])
  assert.deepEqual(d.administradores.map((a) => a.uid), [x.dono.uid])
  assert.equal(d.envelope.objeto.id, p)
  assert.equal(d.voce, null)
  assert.deepEqual(x.s.pageDetail(p, { credencial: x.como(x.dono) }).voce, { segue: false, papel: 'dono' })
  assert.deepEqual(x.s.listedPages({}).itens.map((i) => i.id), [p])
  assert.equal(x.code(x.admin, 'pagina-criar', { nome: 'FÃS de planilha!', descricao: '', tema: 'planilhas' }), 'ja_existe')
  assert.equal(x.code(x.dono, 'pagina-criar', { nome: 'Sem aprovação', descricao: '', tema: 'planilhas' }, { aprovada: false }), 'sem_aprovacao')
  const y = fresh({ novatos: true })
  const newValue = y.rover({ newcomer: true })
  assert.equal(y.code(newValue, 'pagina-criar', { nome: 'Página cedo', descricao: '', tema: 'rovers' }), 'conta_nova')
  y.advance(DAY)
  assert.equal(y.does(newValue, 'pagina-criar', { nome: 'Página cedo', descricao: '', tema: 'rovers' }).estado, 'aceito')
  const z = fresh()
  const a = z.rover()
  for (let i = 0; i < STRUCTURE.pagesAsOwner; i++) { create(z, a, `Página número ${i}`); z.advance(3600 * 8) }
  assert.equal(z.code(a, 'pagina-criar', { nome: 'Página seis', descricao: '', tema: 'rovers' }), 'limite_de_estrutura')
})

test('administrators: only the owner adds and removes; limit of 10; the owner cannot remove themselves; an administrator publishes and updates', () => {
  const x = base()
  const p = create(x, x.dono)
  assert.equal(x.code(x.admin, 'pagina-gestao', { pagina: p, alvo: x.fa.uid, acao: 'adicionar-admin' }), 'sem_permissao')
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' })
  assert.equal(x.code(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' }), 'ja_existe')
  assert.equal(x.code(x.admin, 'pagina-gestao', { pagina: p, alvo: x.fa.uid, acao: 'adicionar-admin' }), 'sem_permissao', 'an administrator does not make administrators')
  assert.equal(x.does(x.admin, 'pagina-atualizar', { pagina: p, nome: 'Fãs de planilha', descricao: 'Descrição nova', tema: 'planilhas' }).estado, 'aceito')
  assert.equal(x.s.pageDetail(p, {}).descricao, 'Descrição nova')
  assert.equal(x.s.pageDetail(p, {}).envelope.objeto.tipo, 'pagina-atualizar')
  assert.equal(x.does(x.admin, 'pagina-publicar', { pagina: p, texto: 'Saiu a versão nova.', tags: [] }).estado, 'aceito')
  assert.equal(x.code(x.fa, 'pagina-publicar', { pagina: p, texto: 'Eu não administro.', tags: [] }), 'sem_permissao')
  assert.equal(x.code(x.fa, 'pagina-atualizar', { pagina: p, nome: 'Sequestrada', descricao: '', tema: 'rovers' }), 'sem_permissao')
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'remover-admin' })
  assert.equal(x.code(x.admin, 'pagina-publicar', { pagina: p, texto: 'Já não administro.', tags: [] }), 'sem_permissao')
  assert.equal(x.code(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'remover-admin' }), 'nao_encontrado')
  for (let i = 0; i < STRUCTURE.adminsPerPage - 1; i++) x.m.store.executar('INSERT INTO pagina_admins (pagina, uid, desde) VALUES (:p, :u, 1)', { p, u: `rvr_${String(i).padStart(22, 'a')}` })
  assert.equal(x.code(x.dono, 'pagina-gestao', { pagina: p, alvo: x.fa.uid, acao: 'adicionar-admin' }), 'limite_de_estrutura')
  assert.equal(x.code(x.dono, 'pagina-gestao', { pagina: p, alvo: x.dono.uid, acao: 'remover-admin' }), 'esquema')
})

test('follow a page: ja_existe, leaving without following, cap of 300; the owner is only notified of a follower with a public graph', () => {
  const x = base()
  const p = create(x, x.dono)
  const closed = x.rover({ grafo: 'privado' })
  x.ok(x.fa, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  assert.equal(x.code(x.fa, 'pagina-seguir', { pagina: p, acao: 'seguir' }), 'ja_existe')
  assert.equal(x.code(x.fa2, 'pagina-seguir', { pagina: p, acao: 'deixar' }), 'nao_encontrado')
  x.ok(closed, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  assert.deepEqual(notices(x, x.dono), ['novo-seguidor'], 'only the public-graph one')
  assert.equal(x.s.listar(x.dono.uid, { limite: 5 }, x.m.relogio.agora).itens[0].pagina, p)
  assert.equal(x.s.pageDetail(p, {}).seguidores, 1, 'the counter only counts whoever keeps the graph public')
  assert.deepEqual(x.s.followersOf(p, {}).itens.map((r) => r.uid), [x.fa.uid])
  assert.equal(x.s.pageDetail(p, { credencial: x.como(x.fa) }).voce.segue, true)
  x.ok(x.fa, 'pagina-seguir', { pagina: p, acao: 'deixar' })
  assert.equal(x.s.pageDetail(p, {}).seguidores, 0)
  const y = base()
  const py = create(y, y.dono)
  for (let i = 0; i < STRUCTURE.followedPages; i++) y.m.store.executar('INSERT INTO pagina_seguidores (pagina, uid, em) VALUES (:p, :u, 1)', { p: `ob_${String(i).padStart(43, 's')}`, u: y.fa.uid })
  assert.equal(y.code(y.fa, 'pagina-seguir', { pagina: py, acao: 'seguir' }), 'limite_de_estrutura')
  assert.equal(y.code(y.fa, 'pagina-seguir', { pagina: `ob_${'A'.repeat(43)}`, acao: 'seguir' }), 'nao_encontrado')
})

test('page updates appear in the timeline of whoever follows, only with tipos=pagina-publicar; the old timeline does not change', () => {
  const x = base()
  const p = create(x, x.dono)
  const friend = x.rover()
  x.ok(x.fa, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  x.ok(x.fa, 'seguir', { alvo: friend.uid })
  const post = x.ok(friend, 'postagem', { texto: 'uma postagem comum', topicos: [] })
  const u1 = x.ok(x.dono, 'pagina-publicar', { pagina: p, titulo: 'Novidade', texto: 'Saiu a versão 2.', tags: ['lancamento'] })
  x.advance(1)
  const u2 = x.ok(x.dono, 'pagina-publicar', { pagina: p, texto: 'Correções.', tags: [] })
  const ids = (types) => x.rele.homeTimeline(x.fa.uid, { tipos: types }).itens.map((e) => e.objeto.id)
  assert.deepEqual(ids(['postagem']), [post.id], 'the 0.2 timeline only brings postagem')
  assert.deepEqual(ids(['pagina-publicar']), [u2.id, u1.id])
  assert.deepEqual(ids(['postagem', 'pagina-publicar']).sort(), [post.id, u1.id, u2.id].sort())
  assert.deepEqual(x.rele.homeTimeline(x.fa.uid, {}).itens.map((e) => e.objeto.id), [post.id])
  assert.equal(codeOf(() => x.rele.homeTimeline(x.fa.uid, { tipos: ['topico'] })), 'esquema')
  assert.equal(codeOf(() => x.rele.homeTimeline(x.fa.uid, { tipos: [] })), 'esquema')
  assert.deepEqual(x.rele.homeTimeline(x.fa2.uid, { tipos: ['pagina-publicar'] }).itens, [], 'whoever does not follow does not see')
  assert.deepEqual(x.s.communityUpdates(p, {}).itens.map((e) => e.objeto.id), [u2.id, u1.id])
  // the closed graph applies to the full timeline
  const f = x.rover({ grafo: 'privado' })
  x.ok(f, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  assert.equal(codeOf(() => x.rele.homeTimeline(f.uid, { tipos: ['pagina-publicar'] })), 'grafo_privado')
  assert.deepEqual(x.rele.homeTimeline(f.uid, { tipos: ['pagina-publicar'], credencial: x.como(f) }).itens.length, 2)
})

test('rover pages: follows and administers, subject to the graph', () => {
  const x = base()
  const p = create(x, x.dono)
  const p2 = create(x, x.admin, 'Outra página')
  x.ok(x.fa, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' })
  const rel = (uid, cred) => x.s.paginasDoRover(uid, { credencial: cred }).itens.map((i) => [i.pagina.id, i.relacao]).sort()
  assert.deepEqual(rel(x.fa.uid, null), [[p, 'seguidor']])
  assert.deepEqual(rel(x.admin.uid, null), [[p, 'administrador'], [p2, 'dono']].sort())
  assert.equal(x.s.paginaDoRover(x.fa.uid, {}).contagens.paginas, 1)
  const f = x.rover({ grafo: 'contagens' })
  x.ok(f, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  assert.equal(codeOf(() => x.s.paginasDoRover(f.uid, {})), 'grafo_privado')
  assert.equal(x.s.paginaDoRover(f.uid, {}).contagens.paginas, 1)
})

test('removing the page (owner only) closes it: gone from the list, the detail, the search and the updates; an administrator cannot remove', () => {
  const x = base()
  const p = create(x, x.dono, 'Página que vai embora')
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' })
  const u = x.ok(x.admin, 'pagina-publicar', { pagina: p, texto: 'Uma atualização.', tags: ['atualizacao'] })
  x.ok(x.fa, 'pagina-seguir', { pagina: p, acao: 'seguir' })
  assert.equal(x.code(x.admin, 'remocao-pelo-autor', { alvo: p }), 'nao_e_autor')
  assert.equal(x.s.buscar({ q: 'embora' }, x.m.relogio.agora).paginas.length, 1)
  x.ok(x.dono, 'remocao-pelo-autor', { alvo: p })
  assert.deepEqual(x.s.listedPages({}).itens, [])
  assert.equal(codeOf(() => x.s.pageDetail(p, {})), 'nao_encontrado')
  assert.equal(codeOf(() => x.s.communityUpdates(p, {})), 'nao_encontrado')
  assert.equal(x.s.buscar({ q: 'embora' }, x.m.relogio.agora).paginas.length, 0)
  assert.deepEqual(x.rele.homeTimeline(x.fa.uid, { tipos: ['pagina-publicar'] }).itens, [])
  assert.equal(codeOf(() => x.rele.objeto(u.id)), 'nao_encontrado', 'the update disappears with it: the page no longer exists')
  assert.equal(x.code(x.admin, 'pagina-publicar', { pagina: p, texto: 'Tarde.', tags: [] }), 'nao_encontrado')
  assert.equal(x.m.store.um('SELECT COUNT(*) AS n FROM tags_uso WHERE objeto = :o', { o: u.id }).n, 0)
})

test('the owner leaves the network: the page goes to the oldest administrator; without an administrator, it closes', () => {
  const x = base()
  const p = create(x, x.dono)
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' })
  x.advance(5)
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.fa.uid, acao: 'adicionar-admin' })
  const solo = create(x, x.fa2, 'Página solitária')
  x.ok(x.dono, 'remocao-pelo-autor', { alvo: x.rele.perfil(x.dono.uid).perfil.id })
  assert.equal(x.s.pageDetail(p, {}).dono.uid, x.admin.uid)
  assert.deepEqual(x.s.pageDetail(p, {}).administradores.map((a) => a.uid), [x.admin.uid, x.fa.uid])
  x.ok(x.fa2, 'remocao-pelo-autor', { alvo: x.rele.perfil(x.fa2.uid).perfil.id })
  assert.equal(codeOf(() => x.s.pageDetail(solo, {})), 'nao_encontrado')
})

test('a page update: the author or the owner remove it; reacting to it works; the #tag marking enters the usage tags', () => {
  const x = base()
  const p = create(x, x.dono)
  x.ok(x.dono, 'pagina-gestao', { pagina: p, alvo: x.admin.uid, acao: 'adicionar-admin' })
  const u = x.ok(x.admin, 'pagina-publicar', { pagina: p, texto: 'Novidade sobre #lancamento hoje', tags: ['versao'] })
  assert.deepEqual(x.m.store.todos('SELECT tag FROM tags_uso WHERE objeto = :o ORDER BY tag', { o: u.id }).map((l) => l.tag), ['lancamento', 'versao'])
  assert.equal(x.does(x.fa, 'reacao', { alvo: u.id, reacao: 'curtir' }).estado, 'aceito')
  assert.equal(x.code(x.fa, 'remocao-pelo-autor', { alvo: u.id }), 'nao_e_autor')
  x.ok(x.admin, 'remocao-pelo-autor', { alvo: u.id })
  assert.equal(x.s.communityUpdates(p, {}).itens.length, 0)
  assert.equal(x.m.store.um('SELECT COUNT(*) AS n FROM tags_uso WHERE objeto = :o', { o: u.id }).n, 0)
  const u2 = x.ok(x.admin, 'pagina-publicar', { pagina: p, texto: 'Outra', tags: [] })
  x.ok(x.dono, 'remocao-por-responsavel', { alvo: u2.id, motivo: 'regras' })
  assert.equal(x.s.communityUpdates(p, {}).itens.length, 0)
  assert.equal(errorOf(() => x.does(x.admin, 'remocao-por-responsavel', { alvo: u2.id, motivo: 'spam' })).codigo, 'sem_permissao')
})
