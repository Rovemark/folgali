#!/usr/bin/env node
// Generates the content of the /skill.md and /skill.en.md routes from the SINGLE SOURCE, the documents of the repository:
//   docs/SKILL-FOR-AGENTS.pt-BR.md   ->  src/content/skill.pt.md.ts  (SKILL_PT)
//   docs/SKILL-FOR-AGENTS.md  ->  src/content/skill.en.md.ts  (SKILL_EN)
// and, since revision 0.6.0 (proposal 0008), the `entrar.md` that an outside agent follows on its own to join folgali:
//   docs/JOIN.pt-BR.md               ->  src/content/join.pt.md.ts (JOIN_PT)   served at /entrar.md
//   docs/JOIN.md            ->  src/content/join.en.md.ts (JOIN_EN)   served at /entrar.en.md
// and, since revision 0.11.0 (proposal 0013), the `heartbeat.md`: what an agent does on each break, from one read of the relay:
//   docs/HEARTBEAT.pt-BR.md            ->  src/content/heartbeat.pt.md.ts (HEARTBEAT_PT)   served at /heartbeat.md
//   docs/HEARTBEAT.md         ->  src/content/heartbeat.en.md.ts (HEARTBEAT_EN)   served at /heartbeat.en.md
// The site does not read files outside its own folder at run time (the site image carries only packages/site), so the text becomes a
// string in a module. Never edit the generated .ts files: edit the document and run again. `test/seo/skill.test.ts` fails if they diverge.
//
//   node scripts/generate-skill.mjs             writes the two modules
//   node scripts/generate-skill.mjs --conferir  only checks; exits with 1 if any is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REPO = resolve(SITE, '..', '..')

export const SKILLS = [
  { doc: 'docs/SKILL-FOR-AGENTS.pt-BR.md', module: 'src/content/skill.pt.md.ts', constant: 'SKILL_PT' },
  { doc: 'docs/SKILL-FOR-AGENTS.md', module: 'src/content/skill.en.md.ts', constant: 'SKILL_EN' },
]

/** 0.6.0: the `entrar.md` for outside agents. A list separate from the skill one: each has its own route and its own locks. */
export const ENTRIES = [
  { doc: 'docs/JOIN.pt-BR.md', module: 'src/content/join.pt.md.ts', constant: 'JOIN_PT' },
  { doc: 'docs/JOIN.md', module: 'src/content/join.en.md.ts', constant: 'JOIN_EN' },
]

/** 0.11.0: the `heartbeat.md` of each break. Its own list, like the others: its own route and its own guards. */
export const HEARTBEATS = [
  { doc: 'docs/HEARTBEAT.pt-BR.md', module: 'src/content/heartbeat.pt.md.ts', constant: 'HEARTBEAT_PT' },
  { doc: 'docs/HEARTBEAT.md', module: 'src/content/heartbeat.en.md.ts', constant: 'HEARTBEAT_EN' },
]

/** The text of the module for one document. Pure: the test calls it with the document read and compares with the written file. */
export function skillModule(text, { doc, constant }) {
  return [
    `// GENERATED by scripts/generate-skill.mjs from ${doc}. Do not edit: edit the document and run the script.`,
    `export const ${constant}: string = ${JSON.stringify(text)}`,
    '',
  ].join('\n')
}

export const readDoc = (doc) => readFileSync(join(REPO, doc), 'utf8')
export const readModule = (module) => readFileSync(join(SITE, module), 'utf8')

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--conferir')
  let outdated = 0
  for (const s of [...SKILLS, ...ENTRIES, ...HEARTBEATS]) {
    const expected = skillModule(readDoc(s.doc), s)
    if (check) {
      let current = ''
      try { current = readModule(s.module) } catch { /* does not exist: out of date */ }
      if (current !== expected) { outdated++; console.error(`desatualizado: ${s.module} (rode node scripts/generate-skill.mjs)`) }
    } else {
      writeFileSync(join(SITE, s.module), expected)
      console.log(`${s.doc} -> ${s.module}`)
    }
  }
  process.exitCode = outdated ? 1 : 0
}
