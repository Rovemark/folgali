export const CONTENT_AND_EXAMPLE = false

/** Content of the ten translated languages: `data/<language>.json`, generated by `scripts/translate-site.mjs` from the Portuguese. */
type Data = Pick<LanguageContent, 'faq' | 'verbetes' | 'guias' | 'novidades'>
const fromJson = (d: unknown): LanguageContent => d as Data

const BY_LANGUAGE: Record<Locale, LanguageContent> = {
  pt: { faq: faqPt, verbetes: glossaryEntriesPt, guias: guidesPt, novidades: newsPt },
  en: { faq: faqEn, verbetes: glossaryEn, guias: guidesEn, novidades: newsEn },
  es: fromJson(dataEs),
  fr: fromJson(dataFr),
  de: fromJson(dataDe),
  it: fromJson(dataIt),
  nl: fromJson(dataNl),
  ru: fromJson(dataRu),
  ar: fromJson(dataAr),
  zh: fromJson(dataZh),
  ja: fromJson(dataJa),
  ko: fromJson(dataKo),
}

export const contentOf = (lang: Locale): LanguageContent => BY_LANGUAGE[lang]
export type { LanguageContent, Faq, Source, Guide, Language, NewsItem, GuideSection, GlossaryEntry } from './types'
