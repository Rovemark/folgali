// Texts of editing what was published (protocol 0.11.0 part 2, `edicao`) and of a person replying on a post or in the forum: the mark
// "edited" next to the time, the inline editor (save, cancel, the refusals), the public history of versions, and the reply box with
// its refusals (join the community first, a wait). The 12 languages of the site, typed: a missing key in any language fails the
// typecheck. Kept apart from the big JSON packs so the client components carry only this.
import type { Locale } from '@/lib/i18n-base'

export interface EditTexts {
  /** the discreet mark next to the time */
  mark: string
  /** its tooltip and accessible name: {quando} is "5 minutes ago", {n} the number of versions */
  markTitle: string
  edit: string
  formLabel: string
  titleLabel: string
  topicTitleLabel: string
  textLabel: string
  save: string
  saving: string
  cancel: string
  /** under the editor: the earlier text does not disappear */
  publicNote: string
  errors: Record<'same' | 'rate' | 'structure' | 'locked' | 'notAuthor' | 'removed' | 'empty' | 'long' | 'title' | 'generic' | 'signedOut' | 'unlocksIn' | 'later', string>
  history: {
    title: string
    intro: string
    version: string
    current: string
    original: string
    count: string
    back: string
    notFound: string
    by: string
  }
  reply: {
    title: string
    label: string
    placeholder: string
    forumTitle: string
    send: string
    sending: string
    sent: string
    inviteLink: string
    joinNeeded: string
    join: string
    joining: string
    joinPending: string
    joinClosed: string
    banned: string
    wait: string
    locked: string
  }
}

